import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import ts from 'typescript';
const code=ts.transpileModule(await readFile(new URL('../src/scene/demoStory.ts',import.meta.url),'utf8'),{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ES2022}}).outputText;
const {flightChanges,demoIntro,demoOutcome,demoCameraCue,demoChangeRows}=await import(`data:text/javascript;base64,${Buffer.from(code).toString('base64')}`);
const pos={x:0,y:0,z:150}, dest={x:200,y:0,z:150};
const flight={position:pos,path:[pos,dest],planned_speed_mps:15,wait_s:0,remaining_distance_m:200,destination:dest,status:'en_route'};
const event={id:'e',kind:'conflict',summary:'延时让行 · A',phase:'resolved',processingMs:1.23};
const result={success:true,presentation:{examples:[{aircraft_id:'A',before:flight,after:{...flight,wait_s:12}}]}};
const state={events:[{id:'e',result}],aircraft:[{id:'A',heading:90,position:pos}],conflicts:[],simulation:{demo_scenario:'weather',time_s:0,tick_seconds:1}};
const changes=flightChanges(state,event);assert.equal(changes[0].after.wait,12);assert.deepEqual(changes[0].before.path,[pos,dest]);
assert(demoOutcome(state,event,changes).decision.includes('0 → 12 s'));assert(demoOutcome(state,event,changes).current.includes('此次预测已解脱'));
assert.equal(demoIntro(state).steps,26);assert.equal(demoIntro(state).countdown,25);assert.deepEqual(demoIntro(state).headings,[1,0,0,0]);
const malformed=structuredClone(state);malformed.events[0].result.presentation.examples[0].before.path.splice(1,0,{x:'bad'});
assert.deepEqual(flightChanges(malformed,event)[0].before.path,[]);
assert.equal(flightChanges(malformed,event)[0].before.pathOmitted,true);
assert.deepEqual(flightChanges({...state,events:[{id:'e',result:{}}]},event),[]);
const areaEvent={...event,kind:'closure',phase:'active',area:{polygon:{points:[{x:-10,y:-10},{x:10,y:-10},{x:10,y:10},{x:-10,y:10}]},minAltitude:100,maxAltitude:200}};
const areaState=structuredClone(state);areaState.events[0].result={affected_aircraft:['A'],evacuating_aircraft:['A'],replanned_aircraft:['A']};
assert(demoOutcome(areaState,areaEvent,[]).current.includes('已撤出 0/1'));
areaState.aircraft[0].position={x:20,y:0,z:150};assert(demoOutcome(areaState,areaEvent,[]).current.includes('已撤出 1/1'));assert(demoOutcome(areaState,areaEvent,[]).current.includes('区域仍生效'));
areaState.events[0].result.paused_for_safety=true;assert.equal(demoOutcome(areaState,areaEvent,[]).current,areaEvent.summary);
console.log('Demo story checks passed: actual waiting change, original geometry, malformed-path rejection, historical fallback, countdown and live evacuation.');

const cueState=structuredClone(state);
cueState.simulation.demo_scenario='weather';
cueState.events.unshift({id:'run',type:'event_info',result:{seed:42,aircraft_count:1,scenario:'weather',camera_cue:{aircraft_id:'A',aircraft_ids:['A'],event_at_s:25,initial_plan:flight}}});
assert.equal(demoCameraCue(cueState).aircraftId,'A');
assert.equal(demoCameraCue(cueState).eventAt,25);
assert.deepEqual(demoCameraCue(cueState).plan.path,[pos,dest]);
cueState.simulation.demo_scenario='failure';assert.equal(demoCameraCue(cueState),null);
assert.equal(demoCameraCue({...state,events:[]}),null);
const rows=demoChangeRows(state,event,changes,'A');
assert.deepEqual(rows.find(r=>r.label==='计划等待'),{label:'计划等待',before:'0 s',after:'12 s'});
console.log('Opening cue and before/after board checks passed: real target, scenario isolation, historical fallback and actual waiting delta.');
